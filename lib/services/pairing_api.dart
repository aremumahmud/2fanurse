import 'dart:convert';
import 'package:http/http.dart' as http;

import 'device_specs.dart';

/// The payload encoded in the admin panel's pairing QR code:
/// {"server": "https://your-deployment", "token": "..."}
class PairingPayload {
  final String server;
  final String token;

  const PairingPayload({required this.server, required this.token});

  static PairingPayload? tryParse(String raw) {
    try {
      final json = jsonDecode(raw) as Map<String, dynamic>;
      final server = json['server'] as String?;
      final token = json['token'] as String?;
      if (server == null || token == null) return null;
      return PairingPayload(server: server, token: token);
    } catch (_) {
      return null;
    }
  }
}

class PairingException implements Exception {
  final String message;
  PairingException(this.message);
  @override
  String toString() => message;
}

class PairingResult {
  final String secret;
  final String label;

  const PairingResult({required this.secret, required this.label});
}

class PairingApi {
  /// Calls the ollama-web backend's public pairing endpoint. No auth needed —
  /// the one-time pairing token generated by the admin is the credential.
  static Future<PairingResult> pair(PairingPayload payload) async {
    final uri = Uri.parse('${payload.server}/api/devices/pair');
    final specs = await DeviceSpecs.current();

    final http.Response response;
    try {
      response = await http
          .post(
            uri,
            headers: {'Content-Type': 'application/json'},
            body: jsonEncode({
              'token': payload.token,
              'platform': specs.platform,
              'model': specs.model,
              'osVersion': specs.osVersion,
            }),
          )
          .timeout(const Duration(seconds: 15));
    } catch (_) {
      throw PairingException('Could not reach $uri. Check the server address and network.');
    }

    final body = jsonDecode(response.body) as Map<String, dynamic>;
    if (response.statusCode != 200) {
      throw PairingException(body['error'] as String? ?? 'Pairing failed');
    }

    return PairingResult(
      secret: body['secret'] as String,
      label: body['label'] as String,
    );
  }
}
